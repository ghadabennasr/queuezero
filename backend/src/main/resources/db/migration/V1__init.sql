-- V1: initial QueueZero schema

CREATE TABLE users (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    email         VARCHAR(255) NOT NULL UNIQUE,
    full_name     VARCHAR(120) NOT NULL,
    password_hash VARCHAR(255) NOT NULL,
    role          VARCHAR(20)  NOT NULL DEFAULT 'USER'
                  CHECK (role IN ('USER', 'SIMULATOR_ADMIN')),
    created_at    TIMESTAMPTZ  NOT NULL DEFAULT now()
);

CREATE TABLE service_categories (
    id   BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code VARCHAR(30) NOT NULL UNIQUE,
    name VARCHAR(80) NOT NULL,
    icon VARCHAR(40)
);

CREATE TABLE service_locations (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    category_id BIGINT NOT NULL REFERENCES service_categories(id),
    name        VARCHAR(150) NOT NULL,
    address     VARCHAR(255),
    governorate VARCHAR(60),
    latitude    DOUBLE PRECISION NOT NULL CHECK (latitude BETWEEN -90 AND 90),
    longitude   DOUBLE PRECISION NOT NULL CHECK (longitude BETWEEN -180 AND 180),
    is_active   BOOLEAN NOT NULL DEFAULT true
);
CREATE INDEX ix_locations_category ON service_locations(category_id);
CREATE INDEX ix_locations_geo ON service_locations(latitude, longitude);

CREATE TABLE opening_hours (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    location_id BIGINT NOT NULL REFERENCES service_locations(id) ON DELETE CASCADE,
    weekday     SMALLINT NOT NULL CHECK (weekday BETWEEN 0 AND 6),
    open_time   TIME,
    close_time  TIME,
    is_closed   BOOLEAN NOT NULL DEFAULT false,
    UNIQUE (location_id, weekday),
    CHECK (is_closed OR (open_time IS NOT NULL AND close_time IS NOT NULL AND open_time < close_time))
);

CREATE TABLE simulation_profiles (
    location_id            BIGINT PRIMARY KEY REFERENCES service_locations(id) ON DELETE CASCADE,
    active_counters        SMALLINT NOT NULL CHECK (active_counters >= 1),
    avg_service_minutes    REAL NOT NULL CHECK (avg_service_minutes > 0),
    base_arrivals_per_hour REAL NOT NULL CHECK (base_arrivals_per_hour >= 0),
    weekday_factors        REAL[] NOT NULL CHECK (cardinality(weekday_factors) = 7),
    hourly_factors         REAL[] NOT NULL CHECK (cardinality(hourly_factors) = 24),
    noise_level            REAL NOT NULL DEFAULT 0.15 CHECK (noise_level >= 0),
    enabled                BOOLEAN NOT NULL DEFAULT true
);

CREATE TABLE queue_snapshots (
    id                     BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    location_id            BIGINT NOT NULL REFERENCES service_locations(id) ON DELETE CASCADE,
    captured_at            TIMESTAMPTZ NOT NULL,
    people_waiting         INT NOT NULL CHECK (people_waiting >= 0),
    active_counters        SMALLINT NOT NULL CHECK (active_counters >= 0),
    avg_service_minutes    REAL NOT NULL CHECK (avg_service_minutes > 0),
    estimated_wait_minutes REAL NOT NULL CHECK (estimated_wait_minutes >= 0),
    source                 VARCHAR(12) NOT NULL DEFAULT 'SIMULATED'
                           CHECK (source IN ('SIMULATED', 'OBSERVED')),
    UNIQUE (location_id, captured_at)
);
CREATE INDEX ix_snapshots_loc_time ON queue_snapshots(location_id, captured_at DESC);

CREATE TABLE queue_predictions (
    id                     BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    location_id            BIGINT NOT NULL REFERENCES service_locations(id) ON DELETE CASCADE,
    made_at                TIMESTAMPTZ NOT NULL,
    target_time            TIMESTAMPTZ NOT NULL,
    predicted_wait_minutes REAL NOT NULL CHECK (predicted_wait_minutes >= 0),
    confidence             VARCHAR(8) NOT NULL CHECK (confidence IN ('LOW', 'MEDIUM', 'HIGH')),
    UNIQUE (location_id, made_at, target_time)
);
CREATE INDEX ix_predictions_target ON queue_predictions(location_id, target_time);

CREATE TABLE favorites (
    user_id     BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    location_id BIGINT NOT NULL REFERENCES service_locations(id) ON DELETE CASCADE,
    created_at  TIMESTAMPTZ NOT NULL DEFAULT now(),
    PRIMARY KEY (user_id, location_id)
);

CREATE TABLE notifications (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id     BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    location_id BIGINT REFERENCES service_locations(id) ON DELETE SET NULL,
    title       VARCHAR(120) NOT NULL,
    body        VARCHAR(400) NOT NULL,
    is_read     BOOLEAN NOT NULL DEFAULT false,
    created_at  TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE INDEX ix_notifications_user ON notifications(user_id, created_at DESC);
